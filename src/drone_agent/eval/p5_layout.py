"""P5 site maps (D069, D071): the M2 campus map plus one registered road segment, written per robot.

Every P5 map is derived from `m2_campus_v2` by text: the registry id, the robot the landing pad is reserved for, one
more prevalidated observation route and the `road_north` asset (a 4 m x 2 m green road marking north of the pad;
`sim/p5_setup.py` adds the same marking to the P5 simulation world). A map may rename its assets with a suffix, so two
sites of one project never register the same asset at two places of the shared frame (D059). Every other route, asset,
threshold and mission default is the M2 one; a test regenerates the files and pins them byte for byte.

P5 站点地图（D069、D071）：M2 园区地图加一处登记道路段，按机器人写出。每张 P5 地图都由 `m2_campus_v2` 按文本派生：登记表
ID、起降点所属机器人、一条新的预验证观察航线与 `road_north` 资产（起降点北侧 4 m × 2 m 的绿色道路段标线；`sim/p5_setup.py`
在 P5 仿真世界中加入同一标线）。地图可以给资产加后缀改名，使同一项目的两个站点不会在共享坐标的两处登记同一资产（D059）。
其余航线、资产、阈值与任务默认值都与 M2 相同；测试重新生成这些文件并逐字节钉住。
"""

from __future__ import annotations

import argparse
from pathlib import Path

BASE = "configs/scenarios/m2_campus_v2.yaml"
# The road marking: centre, extent and the observation pose above it (map_enu, metres).
# 道路段标线：中心、尺寸与其上方的观察位姿（map_enu，米）。
ROAD_CENTRE = (2.0, 8.0)
ROAD_SIZE = (4.0, 2.0)
ROAD_ROUTE = "  observe_road: [[0, 4, 4], [2, 8, 4]]\n"
ROAD_ASSET = """  road_north:
    position: [2, 8, 0]
    camera_id: cam_0
    visual_signature: green
    size_m: 4
    volume: campus_training
    observation_route: observe_road
    kind: road_segment
    description: "Road segment north of the pad, a green marking in simulation / 起降点北侧的道路段，仿真中为绿色标线"
"""
# (file, registry id, robot of the landing pad, asset suffix)
SITES = (
    ("configs/scenarios/p5_site_s1_v1.yaml", "p5_site_s1_v1", "uav_01", ""),
    ("configs/scenarios/p5_site_fa_v1.yaml", "p5_site_fa_v1", "uav_fa", ""),
    ("configs/scenarios/p5_site_fb_v1.yaml", "p5_site_fb_v1", "uav_fb", "_b"),
    ("configs/scenarios/p5_site_vd_v1.yaml", "p5_site_vd_v1", "uav_v1", ""),
)
HEADER = """# P5 site map {registry} (D069, D071), generated by eval/p5_layout.py from m2_campus_v2: the registry id, the landing
# pad's robot ({robot}), the `observe_road` route and the `road_north` road segment{renamed}. Every other route, asset,
# threshold and default is the M2 one; a test regenerates this file and compares it byte for byte.
#
# P5 站点地图 {registry}（D069、D071），由 eval/p5_layout.py 从 m2_campus_v2 生成：登记表 ID、起降点所属机器人（{robot}）、
# `observe_road` 航线与 `road_north` 道路段{renamed_zh}。其余航线、资产、阈值与默认值都与 M2 相同；测试重新生成本文件并逐字节比较。
"""
ASSETS = ("asset_red", "asset_blue", "road_north")


def render(repo: Path, registry: str, robot: str, suffix: str) -> str:
    """One P5 site map as text. / 一张 P5 站点地图的文本。"""
    lines = (repo / BASE).read_text(encoding="utf-8").splitlines(keepends=True)
    body = "".join(line for line in lines[next(i for i, line in enumerate(lines) if line.startswith("schema_version")):])
    replacements = [
        ("registry_id: m2_campus_v2\n", f"registry_id: {registry}\n"),
        ("reserved_for: uav_01}", f"reserved_for: {robot}}}"),
        ("  observe_blue: [[0, 4, 4], [-4, 6, 4]]\n", "  observe_blue: [[0, 4, 4], [-4, 6, 4]]\n" + ROAD_ROUTE),
        ("thresholds:\n", ROAD_ASSET + "thresholds:\n"),
    ]
    for old, new in replacements:
        if body.count(old) != 1:
            raise ValueError(f"the M2 map no longer has exactly one {old.strip()!r}")
        body = body.replace(old, new)
    if suffix:
        for asset in ASSETS:
            if body.count(f"  {asset}:\n") != 1:
                raise ValueError(f"the M2 map no longer has exactly one {asset}")
            body = body.replace(f"  {asset}:\n", f"  {asset}{suffix}:\n")
    renamed = f", assets suffixed {suffix!r}" if suffix else ""
    renamed_zh = f"，资产加后缀 {suffix!r}" if suffix else ""
    return HEADER.format(registry=registry, robot=robot, renamed=renamed, renamed_zh=renamed_zh) + body


def write(repo: Path) -> list[str]:
    written = []
    for path, registry, robot, suffix in SITES:
        target = repo / path
        target.write_bytes(render(repo, registry, robot, suffix).encode("utf-8"))
        written.append(path)
    return written


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[3])
    args = parser.parse_args()
    for path in write(args.root):
        print(path)


if __name__ == "__main__":
    main()
