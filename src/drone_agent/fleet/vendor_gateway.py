"""Vendor mission gateway (P5, D072): authorized high-level tasks to a vendor-managed dock, and what comes back.

The gateway runs inside the mission service and takes a vendor robot's deliveries through the same claim gate as an
onboard uplink (cancel intent, approval expiry, backend, eligibility and reservation re-checked in one transaction).
It verifies the approval signature like the aircraft would, recomputes the vendor task from the approved package and
refuses any task whose digest differs from the one pinned at admission. Each command's transaction id depends only on
(flight, command), so a resend after a lost reply, a broken link or a restart can never start a second execution.

Everything the gateway sends and receives is written as a hash-chained `vendor` journal (the same row format as the
onboard journals, generated by the gateway and labelled as such, never presented as an executive or guardian log);
the service derives each version's state from it. Progress only moves forward by the vendor's sequence number, a
terminal status is never overwritten, duplicates are journaled once. An acknowledgement is receipt; completion needs
the terminal progress and service-verified media; landing needs the vendor's dock state after the terminal. The
vendor's dock state becomes a P1 dock report under the dock's bound identity and its aircraft state a robot status.

厂商任务网关（P5，D072）：把已授权的高层任务交给厂商托管机场，并核对其回报。

网关运行在任务服务内，像机载 uplink 一样经同一领取闸门领取厂商机器人的投递（取消意图、审批有效期、后端、可派遣判定与预约
在一个事务内重查）。它像飞行器一样验证审批签名，由已批准任务包重新推导厂商任务，摘要与准入时固定的不一致即拒绝。每个命令的
事务 ID 只取决于（飞行，命令），因此丢失答复、断线或重启之后的重发永远不会开始第二次执行。

网关发送与收到的一切都写成哈希链的 `vendor` 账本（与机载账本同一行格式，由网关生成并如实标注，从不冒充 executive 或
guardian 日志）；服务据此派生每个版本的状态。进度按厂商序号只前进，终态从不被覆盖，重复报文只入账一次。ACK 只是受理；完成
需要终态进度与服务复核过的媒体；落地需要终态之后的厂商机场状态。厂商机场状态以该机场绑定的身份成为 P1 机场报告，其飞行器
状态成为机器人状态。
"""

